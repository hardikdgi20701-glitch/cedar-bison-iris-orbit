function refuse() {
	return [
		"**No pick, and no target.**",
		"PlanVista will not tell you which stock to buy or sell, and it will not invent a price target.",
		"- Write the goal and the date.",
		"- Read the chart on Chart GPT.",
		"- If you still want to click, use Trade. That fill is practice money only.",
		NOTE
	].join("\n\n");
}
function formatTopic(topic, context) {
	const tape = context.trim() ? context.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("Learner:")).slice(0, 4).join(" ") : "";
	return [
		`**${topic.title}**`,
		topic.lead,
		topic.points.map((p) => `- ${p}`).join("\n"),
		tape ? `Last public print we can see: ${tape}` : "",
		NOTE
	].filter(Boolean).join("\n\n");
}
function openAnswer(prompt, context) {
	const clean = prompt.replace(/\s+/g, " ").trim();
	const tape = context.split("\n").map((l) => l.trim()).filter((l) => /nifty|sensex|bank|viewing|usd|vix/i.test(l)).slice(0, 3).join(" ");
	return [
		`**${clean}**`,
		"Here is the classroom reading. This desk explains. It does not choose a stock for you.",
		"- Say what the words mean before you decide anything.",
		"- If a company is involved, type the name on Research and read support, resistance, and why it last moved.",
		"- If it is a candle or a trend, open Chart GPT and stay on that one symbol.",
		"- If it is a monthly amount or a date, use Goals and the SIP calculator.",
		"- If the move would spend rent or emergency money, do not put it in a share — even as practice.",
		tape ? `Tape in view: ${tape}` : "No live snapshot was attached. Open Home if you want the last Nifty and Sensex print in the next answer.",
		NOTE
	].join("\n\n");
}
function answerQuestion(prompt, context, history = []) {
	const prior = history.filter((m) => m.role === "user").slice(-2).map((m) => m.text).join(" ");
	const asked = prompt.trim();
	const follow = /^(more|aur|batao|explain|simpler|simple|example|why|how|hindi|detail)/i.test(asked);
	const p = `${follow ? prior : ""} ${asked}`.trim().toLowerCase();
	if (/(buy|sell|sure.?shot|recommend|tip do|target do|konsa stock|which stock|intraday call|ye lo)/i.test(asked)) return refuse();
	const hits = TOPICS.filter((t) => t.test.test(p));
	if (hits.length === 1) return formatTopic(hits[0], context);
	if (hits.length > 1) {
		const [a, b] = hits;
		return [
			`**${a.title}**`,
			a.lead,
			a.points.slice(0, 3).map((x) => `- ${x}`).join("\n"),
			`**Also in your question — ${b.title}**`,
			b.lead,
			b.points.slice(0, 2).map((x) => `- ${x}`).join("\n"),
			NOTE
		].join("\n\n");
	}
	if (follow && prior) return openAnswer(prior, context);
	return openAnswer(asked, context);
}
